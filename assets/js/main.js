let currentLang = 'en';
window.translations = translations;
window.currentLang = currentLang;

function setupLanguageToggle() {
  const langToggleBtn = document.getElementById('langToggle');
  if (!langToggleBtn) return;

  // Retrieve language preference from local storage if exists
  const savedLang = localStorage.getItem('site_lang');
  if (savedLang) {
    currentLang = savedLang;
    window.currentLang = currentLang;
    updateLanguage(currentLang);
  }

  langToggleBtn.addEventListener('click', () => {
    currentLang = currentLang === 'en' ? 'hi' : 'en';
    window.currentLang = currentLang;
    localStorage.setItem('site_lang', currentLang);
    updateLanguage(currentLang);
  });
}

function updateLanguage(lang) {
  const btn = document.getElementById('langToggle');
  if (btn) {
    btn.textContent = lang === 'en' ? 'हिन्दी' : 'English';
  }

  const elements = document.querySelectorAll('[data-i18n]');
  elements.forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang] && translations[lang][key]) {
      // Use innerHTML so we can include spans or br tags if needed
      el.innerHTML = translations[lang][key];
    }
  });

  // Re-render product detail page dynamic content
  if (typeof window.renderProductDetail === 'function') {
    window.renderProductDetail(lang);
  }

  // Re-render service detail page dynamic content
  if (typeof window.renderServiceDetail === 'function') {
    window.renderServiceDetail(lang);
  }
}

// Number Counting Animation
function initStatsCounter() {
  const stats = document.querySelectorAll('.stat-card .num[data-target]');
  if (stats.length === 0) return;

  const observerOptions = {
    root: null,
    rootMargin: '0px',
    threshold: 0.1
  };

  const observer = new IntersectionObserver((entries, observer) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        const targetElement = entry.target;
        const targetValue = parseInt(targetElement.getAttribute('data-target'), 10);
        const suffix = targetElement.getAttribute('data-suffix') || '';
        const duration = 2000; // ms
        const frameDuration = 1000 / 60; // 60fps
        const totalFrames = Math.round(duration / frameDuration);
        let frame = 0;

        const counter = setInterval(() => {
          frame++;
          const progress = frame / totalFrames;
          const currentCount = Math.round(targetValue * progress);

          targetElement.textContent = currentCount + suffix;

          if (frame === totalFrames) {
            clearInterval(counter);
            targetElement.textContent = targetValue + suffix;
          }
        }, frameDuration);

        // Stop observing once animation has started
        observer.unobserve(targetElement);
      }
    });
  }, observerOptions);

  stats.forEach(stat => {
    observer.observe(stat);
  });
}

// SCROLL REVEAL ANIMATION (IntersectionObserver)
function initRevealAnimations() {
  const revealElements = document.querySelectorAll('.reveal, .reveal-stagger');
  if (revealElements.length === 0) return;

  const revealObserver = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.classList.add('visible');
        revealObserver.unobserve(entry.target);
      }
    });
  }, { threshold: 0.12, rootMargin: '0px 0px -40px 0px' });

  revealElements.forEach(el => revealObserver.observe(el));
}

// NAVBAR SCROLL SHRINK
function initNavbarScroll() {
  const header = document.getElementById('siteHeader');
  if (!header) return;

  window.addEventListener('scroll', () => {
    if (window.scrollY > 60) {
      header.classList.add('scrolled');
    } else {
      header.classList.remove('scrolled');
    }
  }, { passive: true });
}

// BACK-TO-TOP BUTTON
function initBackToTop() {
  const btn = document.getElementById('backToTop');
  if (!btn) return;

  window.addEventListener('scroll', () => {
    if (window.scrollY > 350) {
      btn.classList.add('visible');
    } else {
      btn.classList.remove('visible');
    }
  }, { passive: true });

  btn.addEventListener('click', () => {
    window.scrollTo({ top: 0, behavior: 'smooth' });
  });
}

// MOBILE HAMBURGER MENU
function initMobileMenu() {
  const hamburger = document.getElementById('hamburgerBtn');
  const navLinks = document.getElementById('navMenu');
  const overlay = document.getElementById('navOverlay');

  if (!hamburger || !navLinks) return;

  function toggleMenu() {
    hamburger.classList.toggle('active');
    navLinks.classList.toggle('open');
    if (overlay) overlay.classList.toggle('active');
    document.body.style.overflow = navLinks.classList.contains('open') ? 'hidden' : '';
  }

  function closeMenu() {
    hamburger.classList.remove('active');
    navLinks.classList.remove('open');
    if (overlay) overlay.classList.remove('active');
    document.body.style.overflow = '';
  }

  hamburger.addEventListener('click', toggleMenu);
  if (overlay) overlay.addEventListener('click', closeMenu);

  // Close menu when a nav link is clicked
  navLinks.querySelectorAll('a').forEach(link => {
    link.addEventListener('click', closeMenu);
  });
}

// Initialize all features safely
function init() {
  setupLanguageToggle();
  initStatsCounter();
  initRevealAnimations();
  initNavbarScroll();
  initBackToTop();
  initMobileMenu();
}

// Execute immediately if DOM is already ready, or wait for DOMContentLoaded
if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', init);
} else {
  init();
}
